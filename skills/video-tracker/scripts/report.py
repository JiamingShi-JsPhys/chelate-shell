"""Markdown report rendering for tracking + FFT outputs.

Pure and fully testable (no OpenCV / numpy required for the table writer;
numpy is optional for numeric formatting of FFT values).
"""

from __future__ import annotations

from pathlib import Path
from typing import Mapping, Sequence


def _fmt(v) -> str:
    if v is None:
        return "-"
    if isinstance(v, float):
        return f"{v:.4g}"
    return str(v)


def _table(rows: Sequence[Sequence]) -> str:
    if not rows:
        return "_(no data)_\n"
    header, body = rows[0], list(rows[1:])
    widths = [
        max([len(str(h))] + [len(str(r[i])) for r in body if i < len(r)])
        for i, h in enumerate(header)
    ]

    def fmt_row(cells):
        return "| " + " | ".join(
            str(c).ljust(widths[i]) for i, c in enumerate(cells)
        ) + " |"

    out = [fmt_row(header), "|" + "|".join("-" * (w + 2) for w in widths)]
    for r in body:
        out.append(fmt_row(r))
    return "\n".join(out) + "\n"


def write_report(summary: Mapping, path: Path) -> Path:
    """Render the tracking summary (+ embedded FFT analyses, if any) to Markdown."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)

    lines = [f"# Tracking report — `{summary.get('video', '?')}`", ""]
    meta = [
        ("FPS", _fmt(summary.get("fps"))),
        ("FPS source", summary.get("fps_source", "-")),
        ("Frames", _fmt(summary.get("n_frames"))),
        (
            "Frame size",
            f"{_fmt(summary.get('frame_width'))}x{_fmt(summary.get('frame_height'))}",
        ),
        ("Scale (cm/px)", _fmt(summary.get("scale_cm_per_px"))),
    ]
    lines += ["## Video", "", _table([("field", "value"), *meta]), ""]

    objects = summary.get("objects", [])
    if objects:
        lines += ["## Objects", ""]
        for o in objects:
            lines += [f"### {o.get('object', '?')}", ""]
            rows = [
                ("metric", "value"),
                ("ROI", f"{o.get('roi', {})}"),
                ("frames_tracked", _fmt(o.get("frames_tracked"))),
                ("success_rate", _fmt(o.get("success_rate"))),
                ("lost_frames", _fmt(o.get("lost_frames"))),
                ("reinit_frames", _fmt(o.get("reinit_frames"))),
                ("tracker_losses", _fmt(o.get("tracker_losses"))),
            ]
            lines += [_table(rows), ""]

    fft = summary.get("fft")
    if fft:
        lines += ["## Spectral analysis", ""]
        for sig, spec in fft.items():
            lines += [f"### {sig}", ""]
            rows = [
                ("metric", "value"),
                ("dominant_freq_hz", _fmt(spec.get("dominant_freq_hz"))),
                ("dominant_amplitude", _fmt(spec.get("dominant_amplitude"))),
                ("period_s", _fmt(spec.get("period_s"))),
                ("top_peaks", _fmt(spec.get("top_peaks"))),
            ]
            lines += [_table(rows), ""]

    lines += ["---", "", f"_Generated by video-tracker. Raw video is never modified._"]
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def write_report_from_files(
    summary_path: Path,
    fft_path: Path | None,
    out_path: Path,
) -> Path:
    """Build a report from already-written summary + FFT JSON files."""
    import json

    summary = json.loads(Path(summary_path).read_text(encoding="utf-8"))
    if fft_path is not None and Path(fft_path).exists():
        fft_data = json.loads(Path(fft_path).read_text(encoding="utf-8"))
        flat = {}
        for sig in fft_data.get("signals", []):
            flat[sig.get("signal", "?")] = sig
        summary["fft"] = flat
    return write_report(summary, out_path)
