"""3d-modeler engine — pure-Python OBJ mesh generation, merge, and audit.

No third-party dependencies: meshes are plain Wavefront OBJ text. The skill
is sandboxed (sandbox_required: true) so a pathological input cannot stall
the pipeline; timeouts return UNVERIFIED, never FAIL.

Public API (used by scripts/run.py):
    build_from_spec(spec_path) -> str   # JSON spec -> OBJ text
    audit_obj(obj_path)       -> str    # validate + normalise an OBJ
    merge_objs(base_text, others) -> str  # concatenate meshes (X-offset)
"""
from __future__ import annotations

import json
import warnings
from pathlib import Path
from typing import List


def _fmt(value: float) -> str:
    """Compact float formatting (6 significant digits)."""
    return f"{float(value):.6g}"


def build_from_spec(spec_path) -> str:
    """Build an OBJ string from a JSON spec.

    Spec shape::

        {"name": "cube",
         "vertices": [[x, y, z], ...],
         "faces": [[i, j, k], ...]}   # indices accepted 0- or 1-based

    Faces are normalised to 1-based OBJ indices.
    """
    data = json.loads(Path(spec_path).read_text(encoding="utf-8"))
    name = data.get("name", "mesh")
    verts = data.get("vertices", [])
    faces = data.get("faces", [])
    if not verts:
        raise ValueError("spec has no vertices")
    lines = [f"# generated by 3d-modeler: {name}", f"o {name}"]
    for v in verts:
        lines.append("v " + " ".join(_fmt(c) for c in v))
    for f in faces:
        idx = [int(i) + (1 if int(i) <= 0 else 0) for i in f]
        lines.append("f " + " ".join(str(i) for i in idx))
    return "\n".join(lines) + "\n"


def audit_obj(obj_path) -> str:
    """Validate and normalise an OBJ file; returns its text after audit.

    .. deprecated::
       Print-quality verification belongs to 3d-fabric
       (``python run.py --action inspect``). This helper only checks
       vertex presence and face index bounds, which is a strict subset.

    Counts vertices/faces and raises ``ValueError`` on out-of-range face
    indices.
    """
    warnings.warn(
        "3d-modeler.audit_obj is deprecated; use 3d-fabric --action inspect",
        DeprecationWarning, stacklevel=2)
    text = Path(obj_path).read_text(encoding="utf-8")
    n_v = sum(1 for ln in text.splitlines() if ln.startswith("v "))
    if n_v == 0:
        raise ValueError("OBJ has no vertices")
    for ln in text.splitlines():
        if not ln.startswith("f "):
            continue
        for tok in ln.split()[1:]:
            i = int(tok.split("/")[0])
            if i < 1 or i > n_v:
                raise ValueError(
                    f"face index {i} out of range (1..{n_v})")
    return text


def merge_objs(base_text: str, others: List) -> str:
    """Append additional OBJ meshes to `base_text`, offsetting each along +X
    by 10 units per merge so the parts do not overlap."""
    parts = [base_text.rstrip("\n")]
    for k, other in enumerate(others, 1):
        text = Path(other).read_text(encoding="utf-8") if not isinstance(
            other, str) else other
        shifted = []
        for ln in text.splitlines():
            if ln.startswith("v "):
                coords = ln.split(maxsplit=1)[1].split()
                coords[0] = _fmt(float(coords[0]) + 10 * k)
                shifted.append("v " + " ".join(coords))
            else:
                shifted.append(ln)
        parts.append("\n".join(shifted))
    return "\n".join(parts) + "\n"
