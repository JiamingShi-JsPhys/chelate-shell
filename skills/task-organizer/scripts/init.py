"""init.py -- lightweight task-folder initialisation.

``init`` is the *cheap* entry point, deliberately decoupled from
``organize``:

=====================================  ========  ==========  ========
Stage                                   init      organize
=====================================  ========  ==========  ========
Build three-tier skeleton              yes       yes
Move existing loose content            yes       yes
Write template ``.task-organizer.yml`` yes       no
SHA-256 snapshots                      **no**    yes
C1-C8 forced verification              **no**    yes
Automatic rollback                     **no**    yes
Operation history / undo               **no**    yes
=====================================  ========  ==========  ========

Rationale: creating a new task should be instant and never leave a
half-built folder behind, so ``init`` does the minimum that makes the
folder *usable* and nothing that could fail expensively.

What "move existing loose content" means
----------------------------------------
If the target folder already contains scattered files or sub-folders from
earlier work, ``init`` lifts them into ``material/initial/`` so the new
task starts from a clean, standard directory:

- loose files -> ``material/initial/<name>``
- sub-folders -> ``material/initial/<dirname>/`` (moved **whole**, never
  recursed into -- scattering a user's sub-tree across the tiers would be
  far more destructive than relocating it intact)

Nothing is ever renamed: a name collision leaves the file where it is and
is reported as a conflict. ``material/initial/`` is reserved for the user's
own material, so the tool can never collide with it.

Every file is registered in the provenance manifest
(``process/sources.json``) as *user material*, which is what later runs use
to guarantee the verbatim behaviour. With ``classify=True`` the placement
rules are applied instead of the "everything to initial" default, so
``final_report.pdf`` lands in ``results/`` -- but registration still marks
the file as the user's, so it is still never renamed.

Every move is recorded in the session and written to the Markdown log under
``process/``, so an ``init`` is auditable even without snapshots.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import List, Optional, Tuple

from scripts import organize, rules as rules_mod, sources as sources_mod, utils
from scripts.utils import logger

#: Name of the config template written by ``init`` when absent.
CONFIG_TEMPLATE_NAME = rules_mod.CONFIG_FILENAME

#: The template written by ``init`` (commented out, safe to edit).
CONFIG_TEMPLATE = """\
# task-organizer placement rules
# ---------------------------------
# This file was generated by `init`. Every value below is commented out, so
# the tool currently uses its built-in rules. Uncomment and edit to override.
#
# Docs: see SKILL.md ("YAML placement-rule config").

# defaults:
#   target: material/initial      # where files with no keyword go

# placement:
#   - priority: 1
#     keywords: [draft, intermediate, temp, tmp, raw]
#     target: process
#   - priority: 2
#     keywords: [final, deliverable]
#     target: results
#   - priority: 3
#     keywords: [download, reference, ref]
#     target: material/downloaded
"""


@dataclass
class InitResult:
    """Outcome of one ``init_folder`` run."""

    root: str
    created_dirs: List[str] = field(default_factory=list)
    moved: List[Tuple[Path, Path, str]] = field(default_factory=list)
    skipped: List[Tuple[Path, str]] = field(default_factory=list)
    config_path: Optional[Path] = None
    log_path: Optional[Path] = None
    broadcast_index_path: Optional[Path] = None
    broadcast_error: Optional[str] = None
    errors: List[str] = field(default_factory=list)

    @property
    def moved_count(self) -> int:
        return len(self.moved)

    @property
    def skipped_count(self) -> int:
        return len(self.skipped)

    @property
    def ok(self) -> bool:
        """True when the skeleton exists and nothing errored."""
        return not self.errors and utils.structure_complete(Path(self.root))

    def summary_lines(self) -> List[str]:
        lines = [f"Root: {self.root}"]
        lines.append("init: done" if self.ok else "init: incomplete")
        if self.created_dirs:
            lines.append(f"created {len(self.created_dirs)} directory(ies)")
        lines.append(f"moved {self.moved_count} existing item(s) into material/initial/")
        if self.skipped_count:
            lines.append(f"skipped {self.skipped_count} item(s)")
        if self.config_path is not None:
            lines.append(f"config: wrote {self.config_path.name}")
        if self.log_path is not None:
            lines.append(f"log: {self.log_path.name}")
        for e in self.errors:
            lines.append(f"  - error: {e}")
        return lines


def _legacy_top_level(root: Path) -> Tuple[List[Path], List[Path], List[Path]]:
    """Split the root's non-owned entries into ``(files, directories, empties)``.

    Hidden files, symlinks and the tool's own three tiers are excluded --
    ``init`` must never touch what it did not create.

    Empty folders are returned separately rather than moved: relocating an
    empty directory into ``initial/`` is pure churn, and :mod:`organize`
    already reports them as "skipped". Keeping the two stages consistent
    matters, because ``init`` is what a user runs first.
    """
    files: List[Path] = []
    dirs: List[Path] = []
    empties: List[Path] = []
    for p in sorted(root.iterdir(), key=lambda x: x.name):
        if utils.is_hidden(p) or p.is_symlink():
            continue
        if p.is_dir():
            if p.name in organize.owned_prefixes():
                continue
            try:
                if not any(p.iterdir()):
                    empties.append(p)
                    continue
            except OSError:
                continue
            dirs.append(p)
        elif p.is_file():
            files.append(p)
    return files, dirs, empties


def write_config_template(root: Path) -> Optional[Path]:
    """Write the commented ``.task-organizer.yml`` template if absent.

    Returns the path when a file was written, ``None`` when one already
    existed (we never overwrite a user's config).
    """
    path = Path(root) / CONFIG_TEMPLATE_NAME
    if path.exists():
        return None
    try:
        path.write_text(CONFIG_TEMPLATE, encoding="utf-8")
        return path
    except OSError as exc:
        logger.warning(f"init: cannot write {path.name} ({exc})")
        return None


def init_folder(
    root: Path,
    rules: Optional[rules_mod.Rules] = None,
    write_config: bool = True,
    classify: bool = False,
    broadcast_after: bool = True,
    verbose: bool = False,
    quiet: bool = False,
) -> InitResult:
    """Create the three-tier skeleton and lift existing content into it.

    Parameters
    ----------
    root:
        The task folder to initialise. Created when missing.
    rules:
        Placement rules used only when *classify* is True. Defaults to the
        built-in table.
    write_config:
        Write the commented ``.task-organizer.yml`` template when absent.
    classify:
        When True, apply the placement rules to legacy loose files instead
        of moving everything into ``material/initial/``. Sub-folders are
        always relocated whole.
    broadcast_after:
        When True (default), build the ``_broadcast/`` context-compression
        index immediately after the skeleton + lift. This is what makes the
        folder carry a navigable map from the very start of the task, so a
        later session reads the index first and opens only the originals it
        needs. Best-effort: a broadcast failure never fails ``init``.
    verbose / quiet:
        Console log switches (the file log is not used by ``init``).

    Returns
    -------
    InitResult:
        Describes the skeleton, the moves and the written config.

    Notes
    -----
    No snapshots are taken and no verification runs -- that is the whole
    point of ``init``. Use ``organize`` (any ``--mode``) when you need the
    forced before/after guarantee.
    """
    root = Path(root).resolve()
    result = InitResult(root=str(root))

    # ---- 0. Logging (console only; init writes no per-day log file). ----
    logger.setup_logging(root, verbose=verbose, quiet=quiet, file_log=False)

    # ---- 0a. Root must exist (create it rather than failing). ----
    try:
        root.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        result.errors.append(f"cannot create root: {exc}")
        return result

    session = utils.OrganizeSession(root=root)

    # ---- 1. Three-tier skeleton (idempotent). ----
    try:
        created = utils.build_structure(root, session)
        result.created_dirs = [str(Path(c).relative_to(root)) for c in created]
        if created:
            logger.info(f"init: created {len(created)} directory(ies)")
    except Exception as exc:  # noqa: BLE001 - init must not crash
        result.errors.append(f"structure build failed: {exc}")
        return result

    # ---- 2. Template config. ----
    if write_config:
        cfg = write_config_template(root)
        if cfg is not None:
            result.config_path = cfg
            session.new_directories.append(str(cfg))
            logger.info(f"init: wrote config template {cfg.name}")

    # ---- 3. Lift existing content. ----
    files, dirs, empties = _legacy_top_level(root)
    for e in empties:
        result.skipped.append((e, "empty folder, not organized"))
    ruleset = rules or rules_mod.builtin_rules()
    man = sources_mod.SourceManifest.load(root)

    # Register everything we find as the user's own material *before* moving,
    # so the verbatim guarantee is recorded even for a folder the user never
    # runs `organize` on.
    man.record_user_files(files)
    for d in dirs:
        man.add(sources_mod.KIND_USER, d.name)

    for src in files:
        if classify:
            target_rel = ruleset.target_for(src.name)
        else:
            target_rel = f"{utils.TIER_ORGANIZE}/{utils.SUB_INIT}"
        target = root / target_rel / src.name
        # User material is never renamed, even in --classify mode.
        ok, msg = organize._move_file(src, target, session, preserve_name=True)
        if ok:
            result.moved.append((src, target, target_rel))
        else:
            result.skipped.append((src, msg))

    for src in dirs:
        if classify:
            target_dir = root / ruleset.target_for(src.name)
        else:
            target_dir = root / utils.TIER_ORGANIZE / utils.SUB_INIT
        ok, msg = organize.move_directory(src, target_dir, session, preserve_name=True)
        if ok:
            result.moved.append(
                (src, target_dir / src.name, str(target_dir.relative_to(root)))
            )
        else:
            result.skipped.append((src, msg))

    # ---- 3a. Persist the provenance manifest. ----
    # Register every file that now lives under the user's zone, including the
    # ones nested inside a relocated folder, so the verbatim guarantee covers
    # the whole tree and not just the top level.
    initial_dir = root / utils.TIER_ORGANIZE / utils.SUB_INIT
    if initial_dir.is_dir():
        for p in sorted(initial_dir.rglob("*")):
            if p.is_file() and not utils.is_hidden(p) and not p.is_symlink():
                man.add(sources_mod.KIND_USER, p.name)
    man.save()
    counts = man.counts()
    if counts.get("user"):
        logger.info(f"init: registered {counts['user']} user file(s)/folder(s)")

    # ---- 4. Audit log (Markdown, no snapshots). ----
    try:
        lines = [f"moved {result.moved_count} existing item(s).", ""]
        for src, tgt, _rule in result.moved:
            lines.append(f"- `{_rel(root, src)}` -> `{_rel(root, tgt)}`")
        if result.skipped:
            lines.append("")
            lines.append(f"skipped {result.skipped_count} item(s):")
            for p, reason in result.skipped:
                lines.append(f"- `{_rel(root, p)}`: {reason}")
        if result.config_path is not None:
            lines.append("")
            lines.append(f"- config template: `{result.config_path.name}`")
        lines.append("")
        lines.append(
            "note: `init` takes no snapshot and runs no verification; "
            "run `organize` when you need the forced before/after guarantee."
        )
        result.log_path = utils.append_log(session, "init", lines)
    except Exception as exc:  # noqa: BLE001
        result.errors.append(f"log write failed: {exc}")

    # ---- 5. Immediate broadcast index (best-effort). ----
    # The user's intent: a task folder should carry a navigable map from the
    # very start, not only after a later `organize`. Build `_broadcast/` now
    # so the next session reads the index first and opens only the originals
    # it needs. This is read-only + idempotent and never fails `init`.
    if broadcast_after:
        try:
            from scripts import broadcast as _bc
            bres = _bc.broadcast(
                root, use_ai=False, max_files=_bc.DEFAULT_MAX_FILES,
                keywords_per_file=_bc.DEFAULT_KEYWORDS,
                verbose=verbose, quiet=quiet,
            )
            if bres.ok:
                result.broadcast_index_path = root / utils.BROADCAST_DIRNAME / "INDEX.md"
                logger.info("init: built _broadcast/ index (immediate map)")
            else:
                result.broadcast_error = "; ".join(bres.errors) or "broadcast incomplete"
                logger.warning(f"init: broadcast index incomplete: {result.broadcast_error}")
        except Exception as exc:  # noqa: BLE001 - broadcast must never fail init
            result.broadcast_error = f"broadcast failed: {exc}"
            logger.warning(f"init: broadcast index skipped ({exc})")

    return result


def _rel(root: Path, p: Path) -> str:
    try:
        return str(Path(p).relative_to(root))
    except ValueError:
        return str(p)
