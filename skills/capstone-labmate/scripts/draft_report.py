#!/usr/bin/env python
"""Stage D — assemble an analysis *draft* from the stage-C summary.

This is the guardrail script of the pipeline. It does NOT generate prose on
its own; it prepares the *input* the host LLM will complete, and it forces
two non-negotiable properties onto whatever draft the host writes:

  1. R-02 randomised error corpus — it randomly samples 2-3 error sources
     from config/error_corpus.json so the wording varies run to run
     (anti-plagiarism). The host model fills the surrounding prose.
  2. R-02 mandatory watermark — the academic-integrity notice is appended
     verbatim to the very end of the draft and CANNOT be stripped.

If a host LLM is not available in-band, this script still emits a structured
skeleton (numbers from summary.json + sampled error sources + watermark) so a
human/teacher always has a complete, honest starting point.

Usage::

    python scripts/draft_report.py \
        --summary work/stage_c/summary.json \
        --corpus config/error_corpus.json \
        --format markdown \
        --out work/stage_d/draft.md \
        [--seed 42]   # seed for reproducible randomisation (optional)
"""

from __future__ import annotations

import argparse
import json
import random
import re
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

# R-02: the watermark is a constant that is ALWAYS appended. It is the last
# thing written and is never optional.
WATERMARK = (
    "*This text was generated by AI as a data analysis reference. "
    "Users must strictly adhere to their institution's academic integrity policies, "
    "independently verify the data, and make final revisions.*"
)

# Marker used to detect and strip existing watermarks to avoid duplication
WATERMARK_MARKER = "This text was generated by AI as a data analysis reference."


def _sample_error_sources(corpus_path: Path, k: int = 3,
                          seed: Optional[int] = None) -> List[Dict[str, Any]]:
    """Randomly pick up to k error-source entries (R-02 randomised corpus)."""
    try:
        data = json.loads(corpus_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        print(f"warning: failed to parse corpus file {corpus_path}: {e}", file=sys.stderr)
        return []
        
    pool = data.get("corpus", [])
    if not pool:
        return []
    rng = random.Random(seed)
    return rng.sample(pool, min(k, len(pool)))


def _fmt(x: Any) -> str:
    if x is None:
        return "n/a"
    if isinstance(x, float):
        return f"{x:.4g}"
    return str(x)


def _build_skeleton(summary: List[Dict[str, Any]], errors: List[Dict[str, Any]]) -> str:
    """A complete, honest draft skeleton: numbers + sampled error sources."""
    lines = ["# Lab Analysis Draft (Data Draft, Manual Review Required)", ""]
    
    for s in summary:
        fit = s.get("fit", {})
        stats = s.get("stats", {})
        lines.append(f"## Series: {s.get('series')}")
        lines.append("")
        lines.append(f"- Raw data points: {s.get('raw_points')}; Down-sampled features: {len(s.get('feature_points', []))}")
        lines.append(f"- Statistics: Mean={_fmt(stats.get('mean'))}, "
                     f"Extrema=[{_fmt(stats.get('min'))}, {_fmt(stats.get('max'))}], "
                     f"StdDev={_fmt(stats.get('std'))}")
        lines.append(f"- Linear Fit: Slope={_fmt(fit.get('slope'))}, "
                     f"Intercept={_fmt(fit.get('intercept'))}, "
                     f"R²={_fmt(fit.get('r_squared'))}")
        lines.append("")
        lines.append("### Phenomenon Description (To be completed by Host LLM)")
        lines.append("*(Host model should complete the phenomenon description based on the numerical values above.)*")
        lines.append("")
        
    lines.append("## Error Analysis (Randomly Sampled Candidates, Manual Verification Required)")
    lines.append("")
    if errors:
        for e in errors:
            lines.append(
                f"- **{e.get('source')}** (Typical magnitude: {e.get('typical_magnitude')}): "
                f"{e.get('phenomenon')}. Possible mechanism: {e.get('mechanism')}.")
    else:
        lines.append("- (Error corpus config/error_corpus.json not provided or empty)")
        
    lines.append("")
    lines.append("### Error Section (To be rewritten by Host LLM)")
    lines.append("*(The randomly sampled items above are candidates; please select and rewrite them according to the actual experiment context.)*")
    lines.append("")
    
    return "\n".join(lines)


def _apply_watermark(text: str) -> str:
    """R-02: strip any existing watermark, then append the canonical one."""
    # Strip existing watermark using the unique marker instead of hardcoded Chinese
    pattern = re.compile(rf"\n*[\*_]*{re.escape(WATERMARK_MARKER)}.*?\n*$", re.S)
    text = pattern.sub("", text).rstrip()
    return text + "\n\n---\n\n" + WATERMARK + "\n"


def run(summary_path: Path, corpus_path: Optional[Path], out_path: Path,
        fmt: str, seed: Optional[int], k: int) -> int:
    out_path = out_path.resolve()
    out_path.parent.mkdir(parents=True, exist_ok=True)

    if not summary_path.exists():
        print(f"error: summary not found at {summary_path}; run stage C first", file=sys.stderr)
        return 2
        
    try:
        summary = json.loads(summary_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as e:
        print(f"error: failed to parse summary file {summary_path}: {e}", file=sys.stderr)
        return 2

    errors: List[Dict[str, Any]] = []
    if corpus_path and Path(corpus_path).exists():
        errors = _sample_error_sources(Path(corpus_path), k, seed)

    draft = _build_skeleton(summary, errors)
    draft = _apply_watermark(draft)  # R-02: watermark is mandatory

    suffix = ".tex" if fmt == "latex" else ".md"
    out = out_path.with_suffix(suffix)
    out.write_text(draft, encoding="utf-8")
    print(f"stage D: {out} ({len(summary)} series, {len(errors)} sampled "
          f"error sources, watermark appended)")
    return 0


def main(argv: Optional[List[str]] = None) -> int:
    p = argparse.ArgumentParser(
        prog="capstone-labmate draft",
        description="Stage D: analysis draft with randomised error corpus + watermark")
    p.add_argument("--summary", required=True, type=Path,
                   help="stage C summary.json")
    p.add_argument("--corpus", type=Path, default=None,
                   help="config/error_corpus.json (optional)")
    p.add_argument("--out", type=Path,
                   default=Path("work/stage_d/draft.md"),
                   help="output draft path")
    p.add_argument("--format", choices=["markdown", "latex"],
                   default="markdown")
    p.add_argument("--seed", type=int, default=None,
                   help="RNG seed for reproducible randomisation (optional)")
    p.add_argument("--n-errors", type=int, default=3,
                   help="how many error sources to sample (default 3)")
    a = p.parse_args(argv)
    return run(a.summary.resolve(),
               a.corpus, a.out.resolve(), a.format, a.seed, a.n_errors)


if __name__ == "__main__":
    raise SystemExit(main())
