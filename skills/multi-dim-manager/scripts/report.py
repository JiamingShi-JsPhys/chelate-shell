"""Render the aggregated results as Markdown tables and a draft report."""

from __future__ import annotations

from pathlib import Path
from typing import Any, Dict, List

from .aggregator import Summary


def _table(rows: List[Dict[str, Any]]) -> str:
    if not rows:
        return "_No rounds recorded._\n"
    cols = list(rows[0].keys())
    head = "| " + " | ".join(str(c) for c in cols) + " |"
    sep = "| " + " | ".join("---" for _ in cols) + " |"
    body = "\n".join(
        "| " + " | ".join(str(r.get(c, "")) for c in cols) + " |" for r in rows
    )
    return head + "\n" + sep + "\n" + body + "\n"


def write_markdown(summary: Summary, path: Path) -> None:
    """Write ``results_summary.md`` (the full results table)."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    content = "# Results Summary\n\n" + _table(summary.rows)
    path.write_text(content, encoding="utf-8")


def write_draft(records: List[Any], summary: Summary, path: Path) -> None:
    """Write ``report_draft.md``: a narrative draft for the user to refine."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    total = len(summary.rows)
    by_status: Dict[str, int] = {}
    for r in summary.rows:
        by_status[r["status"]] = by_status.get(r["status"], 0) + 1
    lines = [
        "# Report Draft",
        "",
        f"- Total rounds executed: **{total}**",
    ]
    for status, count in sorted(by_status.items()):
        lines.append(f"- {status}: **{count}**")
    lines.append("")
    lines.append("## Per-round results")
    lines.append("")
    lines.append(_table(summary.rows))
    lines.append("")
    lines.append("> Draft generated by multi-dim-manager. "
                 "Replace this section with your own analysis.")
    path.write_text("\n".join(lines), encoding="utf-8")
